"""Step 9 acceptance: simulated end-to-end run (scripted LLM, no network).

Covers the whole async_run pipeline: outline → gated section writing with
_set_var in <execute> → polish → reference translation → typed verification →
render-time variable substitution → cedg.json on disk.
"""
import asyncio
import json
import os

from tests.conftest import make_tool_result

OUTLINE = (
    "<outline># 测试公司：业务稳中向好\n\n## 盈利能力拆解\n\n"
    "Writing Advice: 聚焦营收与毛利率，引用利润表数据。</outline>"
)
EXECUTE_CODE = (
    "<execute>\n"
    '_set_var("rev", 99.0, depends_on=["E001"], _code="99.0")\n'
    'print("rev registered")\n'
    "</execute>"
)
DRAFT = (
    "<draft>\n"
    "公司 2024 年营收为 ⟨VAR:rev⟩ 亿元，表现稳健 [Source:E001]。\n\n"
    "公司总部位于北京 [Source:E001]。\n\n"
    "我们认为该趋势将延续。[INFER]\n"
    "</draft>"
)
POLISHED = (
    "公司 2024 年营收为 ⟨VAR:rev⟩ 亿元，表现稳健且结构优异 [Source:E001]。\n\n"
    "公司总部位于北京 [Source:E001]。\n\n"
    "我们认为该趋势将延续。[INFER]\n"
)


class ScriptedLLM:
    def __init__(self):
        self.seen = []

    async def generate(self, messages, stop=None, **kwargs):
        content = messages[-1]['content'] if isinstance(messages, list) else str(messages)
        self.seen.append(content[:80])
        if 'Code execution: success' in content:
            return DRAFT
        if 'Section Outline (Strict Adherence)' in content:
            return EXECUTE_CODE
        if 'research report outline' in content:
            return OUTLINE
        if 'draft to be polished' in content:
            return POLISHED
        if 'Executive Summary' in content:
            return "## 摘要\n\n营收 ⟨VAR:rev⟩ 亿元，稳健增长。\n"
        if 'sell-side research editor' in content:
            return "测试公司：业务稳中向好"
        raise AssertionError(f'scripted LLM got unexpected prompt: {content[:200]}')


def test_simulated_end_to_end_pipeline(report_generator, memory, monkeypatch):
    memory.add_data(make_tool_result('Income statement 2024'))   # E001
    script = ScriptedLLM()
    monkeypatch.setattr(report_generator.llm, 'generate', script.generate)

    import src.agents.report_generator.report_generator as rg_mod
    monkeypatch.setattr(rg_mod.subprocess, 'run', lambda *a, **k: None)
    monkeypatch.setattr(rg_mod.docx2pdf, 'convert', lambda *a, **k: None)

    report = asyncio.run(report_generator.async_run(
        input_data={'task': '写一份测试公司研报', 'target_type': 'financial_company'},
        max_iterations=6,
        resume=False,
    ))

    # --- section body: placeholders rendered, citations translated ---
    body = report.sections[0].content
    assert '⟨VAR:' not in body
    assert '99.00' in body                  # rev (float) rendered with 2 decimals
    assert '[1]' in body                    # [Source:E001] → [1]
    assert '[Source:' not in body
    assert '[待核实]' not in body           # everything verified

    # --- abstract got render-time substitution too ---
    assert '⟨VAR:' not in report.abstract
    assert '99.00' in report.abstract

    # --- reference section generated by direct translation ---
    assert report.sections[-1].title == 'Reference Data Sources'
    assert 'Income statement 2024' in report.sections[-1].content

    # --- markdown written with rendered values ---
    working_dir = report_generator.config.config['working_dir']
    md_path = os.path.join(working_dir, f'{report.title}.md')
    assert os.path.exists(md_path) and os.path.getsize(md_path) > 0
    with open(md_path, encoding='utf-8') as f:
        assert '⟨VAR:' not in f.read()

    # --- CEDG written beside the report with verified claims ---
    cedg_path = os.path.join(working_dir, 'cedg.json')
    assert os.path.exists(cedg_path)
    with open(cedg_path, encoding='utf-8') as f:
        cedg = json.load(f)
    assert len(cedg['claims']) == 3
    nus = {c['nu'] for c in cedg['claims'].values()}
    assert nus == {'verified', 'pending', 'infer'}
    assert cedg['edges']
    assert any(e[2] == 'sup' for e in cedg['edges'])
    assert any(e[2] == 'derive' for e in cedg['edges'])

    # --- registry intact for auditing ---
    assert report_generator.var_registry['rev']['value'] == 99.0
